// facenote.mjs — Face 세션의 첫 요청 앞에만 얇게 붙이는 안내문(터미널 CLI·설정 파일 무접촉).
// 목적: 문서·파일을 "보여줘/띄워줘" 하면 세션 속 에이전트가 실제 파일을 start·기본 앱으로 열지 않고,
//       답변에 파일 경로만 적게 한다 → 화면이 그 경로를 대화 안 미리보기로 삽입한다(원본은 ⧉ 클릭 때만).
// 전달은 CLI 인자가 아니라 첫 요청 본문(괄호 붙여넣기)에 실어 보내므로 한글·공백·유니코드가 깨지지 않는다.
// 대화창에는 안 보이게 transcript 파서가 지운다(아래 stripFaceNote). 첫 요청에만 1회 — 이어지는 맥락에 남는다.
// ⚠ 문자 제약(2026-09-10 실증): 코덱스 TUI는 붙여넣기에서 가운뎃점(·)·원본열기 기호(⧉)·긴줄표(―)를 떨어뜨려 기록파일에 남기지 않는다.
//   그래서 안내문에는 한글·영문·ASCII 문장부호만 쓰고, 지우는 정규식도 끝 표식의 장식 문자에 기대지 않는다.

const OPEN = '[IRIS-Face 안내]';
const END = '-- 아래가 실제 요청이다.';

export const FACE_NOTE =
  `${OPEN} 이 세션은 IRIS-Face 대화 화면에서 실행 중이다. 사용자가 문서나 파일을 "보여줘", "띄워줘"처럼 보기를 요청하면, ` +
  `그 파일을 start, explorer, 기본 앱 등으로 열지 말 것. 대신 답변 본문에 그 파일의 전체 경로를 적기만 하면 ` +
  `화면이 자동으로 대화 안에 미리보기(PDF, 이미지 등)로 넣어 준다. 사용자가 원본 파일 자체를 열고 싶을 때는 ` +
  `미리보기 옆 "원본 열기" 아이콘을 누르면 된다. 사용자가 "원본 파일을 열어라/실행해라"라고 분명히 지시할 때만 실제로 파일을 연다. ` +
  `이 안내는 화면에 표시되지 않는다. ${END}`;

// 첫 요청에 안내문을 앞에 붙인다. 요청이 비었으면(빈 세션) 아무것도 보내지 않는다(안내만 단독으로 보내지 않음).
export function withFaceNote(prompt) {
  const p = (prompt || '').trim();
  return p ? `${FACE_NOTE}\n\n${p}` : '';
}

// 대화 표시용: 사용자 차례 앞머리에 붙은 안내문을 지운다(원문 기록파일은 그대로 둔다).
// 끝 표식은 "아래가 실제 요청이다." 문장만 기준으로 잡는다 — 앞의 장식(옛 `――`, 새 `--`, 코덱스에서 탈락한 빈칸) 어느 형태든 같이 지워진다.
const NOTE_RE = /\[IRIS-Face 안내\][\s\S]*?아래가 실제 요청이다\.\s*/;
export function stripFaceNote(s) {
  return typeof s === 'string' ? s.replace(NOTE_RE, '') : s;
}
